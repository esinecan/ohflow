"""Copy the CONTEXT.md definitions into the written glossary and the map, check them, and check that CONTEXT.md names the vocabulary surface.

    python docs/glossary_sync.py                  # report every disagreement, exit 1 on any
    python docs/glossary_sync.py --write          # rewrite the glossary terms and map definitions
    python docs/glossary_sync.py --accept-surface # record the reviewed public vocabulary surface
"""
from __future__ import annotations

import argparse
import ast
import dataclasses
import importlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTEXT = ROOT / 'CONTEXT.md'
GLOSSARY = ROOT / 'docs/glossary.md'
MAP = ROOT / 'docs/glossary-map.html'
SURFACE = ROOT / 'docs/vocabulary-surface.json'
UNNAMED = ROOT / 'docs/vocabulary-unnamed.json'
SETTINGS = ROOT / 'ohflow.settings.json'
WORKER_SETTINGS = ROOT / 'worker/pi-cloud.settings.json'
CODE = ROOT / 'scripts'
#: The runners whose step ends on another machine; they record the cloud end errors.
REMOTE_RUNNERS = ('pi_cloud_runner.py', 'durable_runner.py', 'cli_cloud_runner.py')
ERROR_PREFIX = re.compile(r'([a-z]+(?:_[a-z]+)*): ')
BEGIN = '<!-- terms: generated by docs/glossary_sync.py from CONTEXT.md; edit CONTEXT.md -->'
END = '<!-- end of generated terms -->'
GRAPH = re.compile(r'(<script type="application/json" id="graph-data">)(.*?)(</script>)', re.S)
ENTRY = re.compile(r'^\*\*(.+?)\*\* — (.+)$')


def terms() -> list[tuple[str, str, str]]:
    section, out = '', []
    for line in CONTEXT.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            section = line[3:].strip()
        elif match := ENTRY.match(line):
            out.append((section, match[1], match[2].strip()))
    return out


def sentence(definition: str) -> str:
    return definition[:1].upper() + definition[1:]


def graph(text: str) -> dict:
    return json.loads(GRAPH.search(text)[2])


def dump_graph(d: dict) -> str:
    rows = lambda items: ',\n'.join('  ' + json.dumps(i, ensure_ascii=False) for i in items)
    return '\n'.join(['{', '"groups": [' + ',\n  '.join(json.dumps(g, ensure_ascii=False) for g in d['groups']) + '],',
                      '"nodes": [', rows(d['nodes']) + '],', '"edges": [', rows(d['edges']) + '],',
                      '"lessons": ' + json.dumps(d['lessons'], ensure_ascii=False, indent=1), '}'])


def synced_map(text: str, defs: dict[str, str]) -> tuple[str, list[str]]:
    d, errors = graph(text), []
    for node in d['nodes']:
        key = node['name'].lower()
        if key not in defs:
            errors.append(f'map node {node["name"]!r} is not a CONTEXT.md term')
        else:
            node['desc'] = sentence(defs[key]).replace('`', '').replace('*', '')
    m = GRAPH.search(text)
    return text[:m.start(2)] + '\n' + dump_graph(d) + '\n' + text[m.end(2):], errors


def glossary_block(entries, codes: dict[str, str]) -> str:
    cell = lambda s: re.sub(r'\]\((?![a-z]+:|/|#)', '](../', s.replace('|', '\\|'))
    out, section = [BEGIN], None
    for sec, term, definition in entries:
        if sec != section:
            section = sec
            out += ['', f'### {sec}', '', '| Term | Definition | Code |', '|---|---|---|']
        code = codes.get(term.lower(), '')
        out.append(f'| {cell(term)} | {cell(sentence(definition))} | {cell(f"`{code}`" if code else "")} |')
    return '\n'.join(out + ['', END])


def synced_glossary(text: str, block: str) -> tuple[str, list[str]]:
    if BEGIN not in text or END not in text:
        return text, [f'{GLOSSARY.name} lacks the generated-terms markers']
    head, rest = text.split(BEGIN, 1)
    return head + block + rest.split(END, 1)[1], []


def python_symbols(path: Path) -> set[str]:
    """Local definitions, class fields and same-file inherited members."""
    symbols: set[str] = set()
    bases: dict[str, list[str]] = {}

    def scan(body, prefix=''):
        for node in body:
            if isinstance(node, ast.ClassDef):
                name = prefix + node.name
                symbols.add(name)
                bases[name] = [ast.unparse(base) for base in node.bases]
                scan(node.body, name + '.')
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                symbols.add(prefix + node.name)
                if prefix:
                    for child in ast.walk(node):
                        if (isinstance(child, ast.Attribute) and isinstance(child.ctx, ast.Store)
                                and isinstance(child.value, ast.Name) and child.value.id in ('self', 'cls')):
                            symbols.add(prefix + child.attr)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                for target in targets:
                    for child in ast.walk(target):
                        if isinstance(child, ast.Name) and isinstance(child.ctx, ast.Store):
                            symbols.add(prefix + child.id)

    scan(ast.parse(path.read_text(encoding='utf-8')).body)
    # Iterate to include inherited fields through multiple local base classes.
    for _ in bases:
        inherited = {name + member[len(base):] for name, parents in bases.items()
                     for base in parents for member in symbols if member.startswith(base + '.')}
        if inherited <= symbols:
            break
        symbols |= inherited
    return symbols


def anchor_errors(d: dict) -> list[str]:
    files = [p for p in [*CODE.rglob('*.py'), *CODE.rglob('*.ts')] if '__pycache__' not in p.parts]
    errors = []
    definitions = {}
    cited = [(f'node {n["name"]!r}', n.get('code', '')) for n in d['nodes']]
    cited += [(f'edge {e["from"]} -> {e["to"]}', e['evidence']) for e in d['edges']]
    for where, text in cited:
        for match in re.finditer(r'([\w/-]+\.(?:py|ts))(?:\s*:\s*([A-Za-z_][\w.]*))?', text):
            paths = [p for p in files if p.as_posix().endswith('/' + match[1])]
            if not paths:
                errors.append(f'{where} cites a missing file {match[1]}')
            elif match[2]:
                symbol = match[2]
                for path in paths:
                    if path not in definitions:
                        if path.suffix == '.py':
                            definitions[path] = python_symbols(path)
                        else:
                            definitions[path] = set(re.findall(
                                r'\bfunction\s+([A-Za-z_$][\w$]*)\s*\(', path.read_text(encoding='utf-8')))
                if not any(symbol in definitions[p] for p in paths):
                    errors.append(f'{where} cites {match[1]}:{match[2]}, which that file does not define')
    return errors


def cli_flags() -> dict[str, list[str]]:
    """Every flag of every verb, read from the parser `cli.build_parser` builds."""
    out: dict[str, list[str]] = {}

    def walk(parser: argparse.ArgumentParser, verb: str) -> None:
        out[f'cli flags: {verb}'] = sorted(
            flag for action in parser._actions for flag in action.option_strings
            if flag not in ('-h', '--help'))
        for action in parser._actions:
            if isinstance(action, argparse._SubParsersAction):
                for name, child in action.choices.items():
                    walk(child, name if verb == 'ohflow' else f'{verb} {name}')

    walk(importlib.import_module('ohflow.cli').build_parser(), 'ohflow')
    return out


def settings_keys(value, prefix: str = '') -> list[str]:
    """The keys of a shipped settings file, a nested object flattened as `a.b`;
    an empty object is a key of its own."""
    if not isinstance(value, dict) or (prefix and not value):
        return [prefix]
    return sorted(key for name, child in value.items()
                  for key in settings_keys(child, f'{prefix}.{name}' if prefix else name))


def _code_trees(names=None):
    package = CODE / 'ohflow'
    paths = [package / name for name in names] if names else sorted(package.rglob('*.py'))
    return [ast.parse(path.read_text(encoding='utf-8')) for path in paths
            if path.is_file() and '__pycache__' not in path.parts]


def _strings(node) -> list[str]:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return [node.value]
    if isinstance(node, ast.IfExp):
        return _strings(node.body) + _strings(node.orelse)
    return []


def cost_sources() -> list[str]:
    """Every literal `cost_source` the code writes: a keyword, a dictionary
    value, a subscript assignment, a parameter default, and what a function
    named `..cost_source` returns."""
    found: set[str] = set()
    for tree in _code_trees():
        for node in ast.walk(tree):
            if isinstance(node, ast.keyword) and node.arg == 'cost_source':
                found.update(_strings(node.value))
            elif isinstance(node, ast.Dict):
                for key, value in zip(node.keys, node.values):
                    if isinstance(key, ast.Constant) and key.value == 'cost_source':
                        found.update(_strings(value))
            elif isinstance(node, ast.Assign):
                if any(isinstance(target, ast.Subscript) and isinstance(target.slice, ast.Constant)
                       and target.slice.value == 'cost_source' for target in node.targets):
                    found.update(_strings(node.value))
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                args = node.args
                positional = [*args.posonlyargs, *args.args]
                defaults = [*zip(positional[len(positional) - len(args.defaults):], args.defaults),
                            *zip(args.kwonlyargs, args.kw_defaults)]
                for arg, default in defaults:
                    if arg.arg == 'cost_source' and default is not None:
                        found.update(_strings(default))
                if node.name.endswith('cost_source'):
                    for child in ast.walk(node):
                        if isinstance(child, ast.Return) and child.value is not None:
                            found.update(_strings(child.value))
    return sorted(found)


def cloud_end_errors() -> list[str]:
    """The `<prefix>: ` that opens an `error` a remote runner assigns."""
    found: set[str] = set()
    for tree in _code_trees(REMOTE_RUNNERS):
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Assign) and any(
                    isinstance(target, ast.Name) and target.id == 'error' for target in node.targets)):
                continue
            first = node.value.values[0] if isinstance(node.value, ast.JoinedStr) and node.value.values else node.value
            if isinstance(first, ast.Constant) and isinstance(first.value, str):
                if match := ERROR_PREFIX.match(first.value):
                    found.add(match[1])
    return sorted(found)


def surface() -> dict[str, list]:
    sys.path.insert(0, str(CODE))
    out: dict[str, list] = {}
    for mod in ('workflow', 'campaign'):
        module = importlib.import_module(f'ohflow.{mod}')
        for name, value in vars(module).items():
            if isinstance(value, type) and dataclasses.is_dataclass(value) and value.__module__ == module.__name__:
                out[f'{mod}.{name}'] = [f.name for f in dataclasses.fields(value)]
    constants = {'workflow': ('BASE_SHA_MODES', 'FAILURE_POLICIES', 'STEP_KINDS', 'HARNESS_EXECUTORS',
                              'FORBIDDEN_RETRY_ON', 'RETRY_BARE_TOKENS'),
                 'run_log': ('STATUSES', 'EVENTS'), 'rundir': ('STOPPED_STATUSES',),
                 'attempts': ('EXCLUSION_THRESHOLD', 'MANUAL_RECOVERY_ALLOWANCE', 'AUTOMATIC_KINDS',
                              'JUDGED_FAILURE_STATUSES'),
                 'retry': ('RETRYABLE_STATUSES',), 'attention': ('GROUPS',)}
    for mod, names in constants.items():
        module = importlib.import_module(f'ohflow.{mod}')
        for name in names:
            value = getattr(module, name)
            out[f'{mod}.{name}'] = sorted(value) if isinstance(value, (set, frozenset)) else (
                list(value) if isinstance(value, (tuple, list)) else [value])
    campaign = ast.parse((CODE / 'ohflow/campaign.py').read_text(encoding='utf-8'))
    states = set()
    for call in ast.walk(campaign):
        if not (isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute)
                and call.func.attr == '_status'):
            continue
        for keyword in call.keywords:
            if keyword.arg == 'state' and isinstance(keyword.value, ast.Constant):
                states.add(keyword.value.value)
            elif keyword.arg is None:
                for expanded in ast.walk(keyword.value):
                    if isinstance(expanded, ast.Dict):
                        states.update(value.value for key, value in zip(expanded.keys, expanded.values)
                                      if isinstance(key, ast.Constant) and key.value == 'state'
                                      and isinstance(value, ast.Constant))
    out['campaign states'] = sorted(states)
    cli = (CODE / 'ohflow/cli.py').read_text(encoding='utf-8')
    out['cli verbs'] = sorted(set(re.findall(r'add_parser\(\s*"([\w-]+)"', cli)) |
                              set(re.findall(r'for name in \(([^)]*)\):\s*\n\s*c = csub\.add_parser', cli)[0]
                                  .replace('"', '').replace(' ', '').split(',')) - {''})
    out.update(cli_flags())
    out['settings keys'] = settings_keys(json.loads(SETTINGS.read_text(encoding='utf-8')))
    out['worker settings keys'] = settings_keys(json.loads(WORKER_SETTINGS.read_text(encoding='utf-8')))
    executors = importlib.import_module('ohflow.harness_executors')
    out['executor capabilities'] = sorted(
        value for name, value in vars(executors).items() if name.startswith('CAP_'))
    out['cost sources'] = cost_sources()
    out['cloud end errors'] = cloud_end_errors()
    return out


def surface_errors() -> list[str]:
    recorded = json.loads(SURFACE.read_text(encoding='utf-8')) if SURFACE.exists() else {}
    current = surface()
    changed = sorted(k for k in current.keys() | recorded.keys() if current.get(k) != recorded.get(k))
    if not changed:
        return []
    return [f'public vocabulary surface changed in {", ".join(changed)}: review CONTEXT.md for the '
            f'changed configuration, command, cost, recovery or status names, then run '
            f'python docs/glossary_sync.py --accept-surface']


def surface_entries(recorded: dict[str, list]) -> list[tuple[str, str]]:
    """Each (part, name) of a surface. A part whose value is a number, such
    as `attempts.EXCLUSION_THRESHOLD`, is named by its constant."""
    return [(part, value if isinstance(value, str) else part.rsplit('.', 1)[-1])
            for part, values in recorded.items() for value in values]


def named_in_context(name: str, spans: str) -> bool:
    """`name` stands in a backtick span alone or after a qualifier, as
    `max_iterations`, `AgentSpec.max_iterations` or `run --hold`."""
    return re.search(rf'(?<![\w-]){re.escape(name)}(?![\w.-])', spans) is not None


def unnamed_errors() -> list[str]:
    recorded = json.loads(SURFACE.read_text(encoding='utf-8')) if SURFACE.exists() else {}
    listed = json.loads(UNNAMED.read_text(encoding='utf-8')) if UNNAMED.exists() else {}
    spans = '\n'.join(re.findall(r'`([^`\n]+)`', CONTEXT.read_text(encoding='utf-8')))
    entries = surface_entries(recorded)
    errors = []
    for part, name in entries:
        reason = listed.get(part, {}).get(name)
        if named_in_context(name, spans):
            if reason is not None:
                errors.append(f'{UNNAMED.name} lists {part}: {name}, which CONTEXT.md names: '
                              f'remove it from the list')
        elif not (isinstance(reason, str) and reason.strip()):
            errors.append(f'surface entry {part}: {name} has no CONTEXT.md name: add `{name}` to '
                          f'a definition in CONTEXT.md, or list it under "{part}" in '
                          f'docs/{UNNAMED.name} with a one-line reason')
    held = set(entries)
    errors += [f'{UNNAMED.name} lists {part}: {name}, which the recorded surface does not hold: '
               f'remove it from the list'
               for part, names in listed.items() for name in names if (part, name) not in held]
    return errors


def run(write: bool) -> list[str]:
    entries = terms()
    defs = {term.lower(): definition for _, term, definition in entries}
    errors = [f'CONTEXT.md defines {term!r} twice' for term in defs
              if sum(t.lower() == term for _, t, _ in entries) > 1]
    map_text = MAP.read_text(encoding='utf-8')
    new_map, map_errors = synced_map(map_text, defs)
    codes = {n['name'].lower(): n.get('code', '') for n in graph(new_map)['nodes']}
    glossary_text = GLOSSARY.read_text(encoding='utf-8')
    new_glossary, glossary_errors = synced_glossary(glossary_text, glossary_block(entries, codes))
    errors += (map_errors + glossary_errors + anchor_errors(graph(new_map)) + surface_errors()
               + unnamed_errors())
    if write:
        MAP.write_text(new_map, encoding='utf-8', newline='\n')
        GLOSSARY.write_text(new_glossary, encoding='utf-8', newline='\n')
    else:
        if new_map != map_text:
            errors.append('docs/glossary-map.html definitions differ from CONTEXT.md: run python docs/glossary_sync.py --write')
        if new_glossary != glossary_text:
            errors.append('docs/glossary.md terms differ from CONTEXT.md: run python docs/glossary_sync.py --write')
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--accept-surface', action='store_true')
    args = parser.parse_args()
    if args.accept_surface:
        SURFACE.write_text(json.dumps(surface(), indent=1, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')
    errors = run(args.write)
    for error in errors:
        print('FAIL', error)
    recorded = json.loads(SURFACE.read_text(encoding='utf-8')) if SURFACE.exists() else {}
    listed = json.loads(UNNAMED.read_text(encoding='utf-8')) if UNNAMED.exists() else {}
    print('FAIL' if errors else 'PASS', f'{len(terms())} CONTEXT.md terms, '
          f'{len(surface_entries(recorded))} surface entries, '
          f'{sum(len(names) for names in listed.values())} listed unnamed')
    return bool(errors)


if __name__ == '__main__':
    raise SystemExit(main())
